    static final int DEFAULT_RING = ItemID.NZONE_BERZERKER_RING;
    private static final Map<Integer, Gear> BY_ID = new HashMap<>();

    static
    {
        for (Gear g : values())
        {
            for (int id : g.ids) BY_ID.putIfAbsent(id, g);
        }
    }

    /** The item whose stats count. */
    final int id;
    private final int[] ids;

    Gear(int... ids)
    {
        this.id = ids[0];
        this.ids = ids;
    }

    static Gear of(int itemId)
    {
        return BY_ID.get(itemId);
    }

    /** The ammo a weapon fires: the worn ammo when it suits the weapon, else the weapon's usual ammo; null for none. */
    static Ammo ammo(Gear weapon, int worn)
    {
        Ammo a = Ammo.of(worn);
        return a != null && fits(weapon, a) ? a : usual(weapon);
    }

    private static boolean fits(Gear w, Ammo a)
    {
        if (w == RUNE_CROSSBOW) return a.kind == Ammo.BOLT;
        if (w == ARMADYL_CROSSBOW || w == DRAGON_CROSSBOW || w == DRAGON_HUNTER_CROSSBOW || w == ZARYTE_CROSSBOW)
            return a.kind == Ammo.DRAGON_BOLT;
        if (w == HEAVY_BALLISTA || w == LIGHT_BALLISTA) return a == Ammo.DRAGON_JAVELIN;
        if (w == TOXIC_BLOWPIPE) return a.kind == Ammo.DART;
        if (w == DARK_BOW || w == MAGIC_SHORTBOW || w == MAGIC_SHORTBOW_I || w == SCORCHING_BOW)
            return a == Ammo.AMETHYST_ARROWS || a == Ammo.DRAGON_ARROW || a.seeking();
        if (w == KARILS_CROSSBOW) return a == Ammo.BOLT_RACK;
        return w == HUNTERS_SUNLIGHT_CROSSBOW && a == Ammo.MOONLIGHT_ANTLER_BOLTS;
    }

    private static Ammo usual(Gear w)
    {
        if (w == RUNE_CROSSBOW) return Ammo.DIAMOND_BOLTS_E;
        if (w == ARMADYL_CROSSBOW || w == DRAGON_CROSSBOW || w == DRAGON_HUNTER_CROSSBOW || w == ZARYTE_CROSSBOW)
            return Ammo.OPAL_DRAGON_BOLTS_E;
        if (w == TOXIC_BLOWPIPE) return Ammo.DRAGON_DARTS;
        if (w == HEAVY_BALLISTA || w == LIGHT_BALLISTA) return Ammo.DRAGON_JAVELIN;
        if (w == DARK_BOW || w == SCORCHING_BOW) return Ammo.DRAGON_ARROW;
        if (w == KARILS_CROSSBOW) return Ammo.BOLT_RACK;
        if (w == HUNTERS_SUNLIGHT_CROSSBOW) return Ammo.MOONLIGHT_ANTLER_BOLTS;
        return w == MAGIC_SHORTBOW || w == MAGIC_SHORTBOW_I ? Ammo.AMETHYST_ARROWS : null;
    }

